#!/usr/bin/env python3
"""
make_lane_designs.py -- create one LibreLane design folder per LANES value.

AI note: written by Claude (Anthropic) for Ryan Hall's FIR_Filter project.

For each N it writes
    asic/lanes<N>/fir_lanes<N>.v   two-line wrapper: FIR_Core_MAC with LANES fixed to N
    asic/lanes<N>/config.json      copy of asic/serial_mac/config.json, DESIGN_NAME = the wrapper
The wrapper has the same ports as FIR_Core_MAC, so the ASIC results are the core itself.
Using a wrapper (instead of a tool-specific parameter override) works with any LibreLane
version, and the RTL files are shared, so every lane count builds from the same source.

Usage (from the repo root):
    python asic/scripts/make_lane_designs.py                 # 1 2 4 8 16
    python asic/scripts/make_lane_designs.py --lanes 1 4 32
Existing folders are overwritten (their runs/ subfolders are left alone).
"""
import argparse, json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

WRAPPER = """//****************************************************
// GENERATED FILE - do not edit. Run asic/scripts/make_lane_designs.py
// AI note     : generated by a script written by Claude (Anthropic).
//
// ASIC top for LANES = {n}: FIR_Core_MAC (written by Ryan Hall) with LANES fixed,
// same ports. Exists only so LibreLane can build a given lane count.
//****************************************************
module fir_lanes{n} (
    input  wire               clk,
    input  wire               rst,
    input  wire               sample_valid,
    input  wire signed [15:0] sample_in,
    input  wire        [1:0]  ch_select,
    output wire signed [15:0] sample_out,
    output wire               out_valid
);
    FIR_Core_MAC #(
        .COEF_W    (16),
        .SAMPLE_W  (16),
        .ACC_W     (39),
        .SHIFT     (16),
        .TAP_COUNT (59),
        .LANES     ({n})
    ) u_core (
        .clk          (clk),
        .rst          (rst),
        .sample_valid (sample_valid),
        .sample_in    (sample_in),
        .ch_select    (ch_select),
        .sample_out   (sample_out),
        .out_valid    (out_valid)
    );
endmodule
"""

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lanes", nargs="+", type=int, default=[1, 2, 4, 8, 16])
    a = ap.parse_args()
    base = json.loads((REPO / "asic/serial_mac/config.json").read_text())
    for n in a.lanes:
        d = REPO / f"asic/lanes{n}"
        d.mkdir(parents=True, exist_ok=True)
        (d / f"fir_lanes{n}.v").write_text(WRAPPER.format(n=n))
        cfg = dict(base)
        cfg["DESIGN_NAME"] = f"fir_lanes{n}"
        cfg["VERILOG_FILES"] = [f"dir::fir_lanes{n}.v"] + list(base["VERILOG_FILES"])
        (d / "config.json").write_text(json.dumps(cfg, indent=2) + "\n")
        print(f"wrote asic/lanes{n}/ (fir_lanes{n}.v, config.json)")

if __name__ == "__main__":
    main()
